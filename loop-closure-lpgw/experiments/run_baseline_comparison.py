    print("[4/4] Computing Hausdorff distance matrix...")
    print("=" * 70)

    start_time = time.perf_counter()

    D_hausdorff = compute_hausdorff_matrix(
        query_baseline_segments,
        reference_baseline_segments,
    )

    hausdorff_time = (
        time.perf_counter() - start_time
    )

    print(
        f"Hausdorff matrix computed in "
        f"{hausdorff_time:.3f} s"
    )

    print(
        f"Hausdorff matrix shape: "
        f"{D_hausdorff.shape}"
    )

    for percentile in percentiles:

        _, metrics = evaluate_distance_matrix(
            D_hausdorff,
            y_true,
            percentile,
        )

        print(
            f"Hausdorff @{percentile}%: "
            f"P={metrics['precision']:.3f}, "
            f"R={metrics['recall']:.3f}, "
            f"F1={metrics['f1']:.3f}"
        )

        rows.append({
            "dataset": config.ACTIVE_DATASET,
            "method": "Hausdorff",
            "percentile": percentile,
            "precision": metrics["precision"],
            "recall": metrics["recall"],
            "f1": metrics["f1"],
            "tp": metrics["tp"],
            "fp": metrics["fp"],
            "fn": metrics["fn"],
            "threshold_tau": metrics["threshold_tau"],
            "num_predicted_positive": (
                metrics["num_predicted_positive"]
            ),
            "runtime_sec": hausdorff_time,
            "num_query_segments": len(
                query_segments
            ),
            "num_reference_segments": len(
                reference_segments
            ),
            "baseline_policy": (
                config.BASELINE_SEGMENT_POLICY
            ),
            "seed": config.RANDOM_SEED,
            "ground_truth": "canonical",
        })

    # ========================================================
    # Save results
    # ========================================================

    results_df = pd.DataFrame(rows)

    output_dir = Path("results")

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    output_path = (
        output_dir
        / (
            f"baseline_accuracy_"
            f"{config.DATASET_SHORT}.csv"
        )
    )

    results_df.to_csv(
        output_path,
        index=False,
    )

    # ========================================================
    # Final summary
    # ========================================================

    print("\n" + "=" * 70)
    print("BASELINE COMPARISON COMPLETE")
    print("=" * 70)

    print(
        f"\nCanonical ground-truth positives: "
        f"{np.sum(y_true)} / {len(y_true)}"
    )

    print(
        f"Reference segments used: "
        f"{len(reference_segments)}"
    )

    print(
        f"Query segments used: "
        f"{len(query_segments)}"
    )

    print(
        "\nGround truth source:"
    )

    print(
        f"  gt_{config.DATASET_SHORT}_"
        f"{config.SPATIAL_TOLERANCE}m.csv"
    )

    print(
        f"\nResults saved to:\n"
        f"{output_path}"
    )

    print("\nSummary:")

    print(
        results_df[
            [
                "method",
                "percentile",
                "precision",
                "recall",
                "f1",
                "threshold_tau",
                "num_predicted_positive",
            ]
        ].to_string(index=False)
    )

    return results_df


