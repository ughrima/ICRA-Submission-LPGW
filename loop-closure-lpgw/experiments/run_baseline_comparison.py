def discrete_frechet_distance(curve1, curve2):
    """
    Discrete Frechet distance between two 3D curves.
    """

    n = len(curve1)
    m = len(curve2)

    if n == 0 or m == 0:
        return np.inf

    ca = np.full(
        (n, m),
        np.inf,
        dtype=float,
    )

    for i in range(n):
        for j in range(m):

            d = np.linalg.norm(
                curve1[i] - curve2[j]
            )

            if i == 0 and j == 0:

                ca[i, j] = d

            elif i == 0:

                ca[i, j] = max(
                    ca[i, j - 1],
                    d,
                )

            elif j == 0:

                ca[i, j] = max(
                    ca[i - 1, j],
                    d,
                )

            else:

                ca[i, j] = max(
                    min(
                        ca[i - 1, j],
                        ca[i - 1, j - 1],
                        ca[i, j - 1],
                    ),
                    d,
                )

    return ca[n - 1, m - 1]


