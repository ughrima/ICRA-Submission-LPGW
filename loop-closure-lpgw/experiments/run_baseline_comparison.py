def dtw_distance(seq1, seq2):
    """
    Standard dynamic time warping distance between two 3D curves.
    """

    n = len(seq1)
    m = len(seq2)

    if n == 0 or m == 0:
        return np.inf

    cost = np.full(
        (n + 1, m + 1),
        np.inf,
        dtype=float,
    )

    cost[0, 0] = 0.0

    for i in range(1, n + 1):
        for j in range(1, m + 1):

            d = np.linalg.norm(
                seq1[i - 1] - seq2[j - 1]
            )

            cost[i, j] = d + min(
                cost[i - 1, j],
                cost[i, j - 1],
                cost[i - 1, j - 1],
            )

    return cost[n, m]


def compute_dtw_matrix(query_segments, reference_segments):
    """
    Compute complete DTW distance matrix.

    Shape:
        [N_query, N_reference]

    D[i, j] =
        DTW(query_segments[i], reference_segments[j])
    """

    n_query = len(query_segments)
    n_reference = len(reference_segments)

    D = np.zeros(
        (n_query, n_reference),
        dtype=float,
    )

    for i in range(n_query):

        if (
            (i + 1) % 10 == 0
            or i == 0
            or i == n_query - 1
        ):
            print(
                f"  DTW row {i + 1}/{n_query}",
                flush=True,
            )

        for j in range(n_reference):

            D[i, j] = dtw_distance(
                query_segments[i],
                reference_segments[j],
            )

    return D


