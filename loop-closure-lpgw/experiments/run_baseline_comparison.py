def select_baseline_subset(segments, max_segments, rng):
    """
    Deterministically select a subset of segments.

    Returns:
        selected_segments:
            Selected trajectory segments.

        selected_indices:
            Original indices of the selected segments.

    The indices are sorted so temporal ordering is preserved.
    """

    n = len(segments)

    if n <= max_segments:
        indices = np.arange(n, dtype=int)
    else:
        indices = rng.choice(
            n,
            size=max_segments,
            replace=False,
        )
        indices = np.sort(indices)

    selected_segments = [segments[i] for i in indices]

    return selected_segments, indices


