def main():

    print("=" * 70)
    print("FULL-SCALE LPGW LOOP-CLOSURE EXPERIMENT")
    print("=" * 70)

    print(
        f"Dataset: {config.ACTIVE_DATASET}"
    )

    print(
        f"Percentiles: {config.PERCENTILE_SWEEP}"
    )

    print(
        f"LPGW lambda: {config.LPGW_LAMBDA}"
    )

    print(
        f"Target points: {config.TARGET_POINTS}"
    )

    print(
        f"Segment length: {config.SEGMENT_LENGTH} s"
    )

    print(
        f"Stride: {config.STRIDE} s"
    )


    # ========================================================
    # 1. Load trajectories
    # ========================================================

    print("\n" + "=" * 70)
    print("1. LOADING TRAJECTORIES")
    print("=" * 70)

    reference_path = (
        Path(config.POSES_DIR)
        / config.BAG3_CSV
    )

    query_path = (
        Path(config.POSES_DIR)
        / config.BAG7_CSV
    )

    print(f"Reference: {reference_path}")
    print(f"Query:     {query_path}")

    reference_df = load_trajectory(
        reference_path
    )

    query_df = load_trajectory(
        query_path
    )

    reference_xyz = reference_df[
        ["PosX", "PosY", "PosZ"]
    ].to_numpy()

    query_xyz = query_df[
        ["PosX", "PosY", "PosZ"]
    ].to_numpy()

    print(
        f"Reference raw points: {len(reference_xyz)}"
    )

    print(
        f"Query raw points:     {len(query_xyz)}"
    )


    # ========================================================
    # 2. Canonical preprocessing
    # ========================================================

    print("\n" + "=" * 70)
    print("2. CANONICAL PREPROCESSING")
    print("=" * 70)

    print(
        f"Downsampling both trajectories to "
        f"{config.TARGET_POINTS} points..."
    )

    reference_xyz = downsample_trajectory(
        reference_xyz,
        config.TARGET_POINTS,
    )

    query_xyz = downsample_trajectory(
        query_xyz,
        config.TARGET_POINTS,
    )

    print(
        f"Reference points after preprocessing: "
        f"{len(reference_xyz)}"
    )

    print(
        f"Query points after preprocessing:     "
        f"{len(query_xyz)}"
    )


    # ========================================================
    # 3. Segment trajectories
    # ========================================================

    print("\n" + "=" * 70)
    print("3. SEGMENTING TRAJECTORIES")
    print("=" * 70)

    reference_segments = segment_trajectory(
        reference_xyz,
        segment_length=config.SEGMENT_LENGTH,
        fps=config.FPS,
        stride=config.STRIDE,
    )

    query_segments = segment_trajectory(
        query_xyz,
        segment_length=config.SEGMENT_LENGTH,
        fps=config.FPS,
        stride=config.STRIDE,
    )

    print(
        f"Reference segments before alignment: "
        f"{len(reference_segments)}"
    )

    print(
        f"Query segments before alignment: "
        f"{len(query_segments)}"
    )

    if len(reference_segments) == 0:
        raise RuntimeError(
            "No reference segments were generated."
        )

    if len(query_segments) == 0:
        raise RuntimeError(
            "No query segments were generated."
        )


    # ========================================================
    # 4. Canonical alignment
    # ========================================================

    min_len = min(
        len(reference_segments),
        len(query_segments),
    )

    reference_segments = (
        reference_segments[:min_len]
    )

    query_segments = (
        query_segments[:min_len]
    )

    print("\nAfter canonical alignment:")

    print(
        f"Reference segments: "
        f"{len(reference_segments)}"
    )

    print(
        f"Query segments: "
        f"{len(query_segments)}"
    )


    # ========================================================
    # 5. Load canonical GT
    # ========================================================

    print("\n" + "=" * 70)
    print("4. LOADING CANONICAL GROUND TRUTH")
    print("=" * 70)

    y_true = load_canonical_ground_truth(
        num_query_segments=len(query_segments)
    )


    # ========================================================
    # 6. Create LPGW detector
    # ========================================================

    print("\n" + "=" * 70)
    print("5. INITIALIZING LPGW")
    print("=" * 70)

    detector = LoopClosureDetector(
        segment_length=config.SEGMENT_LENGTH,
        fps=config.FPS,
        stride=config.STRIDE,
        lambdaa=config.LPGW_LAMBDA,
        downsample_points=config.TARGET_POINTS,
        reference_strategy="first",
    )

    print("LPGW detector initialized.")
    print(
        f"Lambda = {config.LPGW_LAMBDA}"
    )


    # ========================================================
    # 7. Compute FULL LPGW distance matrix
    # ========================================================

    print("\n" + "=" * 70)
    print("6. COMPUTING FULL LPGW DISTANCE MATRIX")
    print("=" * 70)

    print(
        f"Query segments:     {len(query_segments)}"
    )

    print(
        f"Reference segments: {len(reference_segments)}"
    )

    print(
        f"Total pairwise comparisons: "
        f"{len(query_segments) * len(reference_segments)}"
    )

    print("\nThis may take a few seconds...")

    start_time = time.perf_counter()

    # IMPORTANT:
    #
    # LoopClosureDetector expects:
    #
    #     segments1 = query
    #     segments2 = reference

    D_lpgw = detector.compute_distance_matrix(
        query_segments,
        reference_segments,
    )

    runtime_sec = (
        time.perf_counter() - start_time
    )

    print(
        f"\nLPGW matrix computed in "
        f"{runtime_sec:.3f} seconds"
    )

    print(
        f"Distance matrix shape: "
        f"{D_lpgw.shape}"
    )

    if D_lpgw.shape != (
        len(query_segments),
        len(reference_segments),
    ):
        raise RuntimeError(
            "Unexpected LPGW distance matrix shape."
        )

    if not np.all(np.isfinite(D_lpgw)):
        raise RuntimeError(
            "LPGW distance matrix contains "
            "NaN or infinite values."
        )


    # ========================================================
    # 8. Evaluate
    # ========================================================

    print("\n" + "=" * 70)
    print("7. EVALUATING LPGW")
    print("=" * 70)

    rows = []

    for percentile in config.PERCENTILE_SWEEP:

        _, metrics = evaluate_distance_matrix(
            D_lpgw,
            y_true,
            percentile,
        )

        print(
            f"\nLPGW @{percentile}%"
        )

        print(
            f"  Precision: "
            f"{metrics['precision']:.3f}"
        )

        print(
            f"  Recall:    "
            f"{metrics['recall']:.3f}"
        )

        print(
            f"  F1:        "
            f"{metrics['f1']:.3f}"
        )

        print(
            f"  Threshold: "
            f"{metrics['threshold_tau']:.6f}"
        )

        print(
            f"  Predicted positives: "
            f"{metrics['num_predicted_positive']}"
        )

        rows.append({
            "dataset": config.ACTIVE_DATASET,
            "method": "LPGW",
            "percentile": percentile,

            "precision": metrics["precision"],
            "recall": metrics["recall"],
            "f1": metrics["f1"],

            "tp": metrics["tp"],
            "fp": metrics["fp"],
            "fn": metrics["fn"],

            "threshold_tau":
                metrics["threshold_tau"],

            "num_predicted_positive":
                metrics["num_predicted_positive"],

            "runtime_sec": runtime_sec,

            "num_query_segments":
                len(query_segments),

            "num_reference_segments":
                len(reference_segments),

            "segment_length_sec":
                config.SEGMENT_LENGTH,

            "stride_sec":
                config.STRIDE,

            "target_points":
                config.TARGET_POINTS,

            "lambda":
                config.LPGW_LAMBDA,

            "spatial_tolerance_m":
                config.SPATIAL_TOLERANCE,

            "ground_truth":
                "canonical",
        })


    # ========================================================
    # 9. Save results
    # ========================================================

    print("\n" + "=" * 70)
    print("8. SAVING RESULTS")
    print("=" * 70)

    results_df = pd.DataFrame(rows)

    output_dir = Path("results")
    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    output_path = (
        output_dir
        / (
            f"full_lpgw_"
            f"{config.DATASET_SHORT}.csv"
        )
    )

    results_df.to_csv(
        output_path,
        index=False,
    )

    print(
        f"\nResults saved to:\n"
        f"  {output_path}"
    )


    # ========================================================
    # 10. Final summary
    # ========================================================

    print("\n" + "=" * 70)
    print("FULL-SCALE LPGW EXPERIMENT COMPLETE")
    print("=" * 70)

    print(
        f"\nDataset: "
        f"{config.ACTIVE_DATASET}"
    )

    print(
        f"Query segments: "
        f"{len(query_segments)}"
    )

    print(
        f"Reference segments: "
        f"{len(reference_segments)}"
    )

    print(
        f"Canonical GT positives: "
        f"{np.sum(y_true)} / {len(y_true)}"
    )

    print(
        f"LPGW runtime: "
        f"{runtime_sec:.3f} seconds"
    )

    print("\nSummary:")

    print(
        results_df[
            [
                "method",
                "percentile",
                "precision",
                "recall",
                "f1",
                "threshold_tau",
                "num_predicted_positive",
            ]
        ].to_string(index=False)
    )

    return results_df


# ============================================================
# Entry point
# ============================================================

if __name__ == "__main__":
    main()