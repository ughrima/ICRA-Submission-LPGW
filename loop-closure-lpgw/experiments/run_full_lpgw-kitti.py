def precision_recall_f1(y_true, y_pred):
    """
    Compute precision, recall and F1.
    """

    y_true = np.asarray(y_true, dtype=bool)
    y_pred = np.asarray(y_pred, dtype=bool)

    if len(y_true) != len(y_pred):
        raise ValueError(
            "y_true and y_pred must have the same length."
        )

    tp = np.sum(y_true & y_pred)
    fp = np.sum(~y_true & y_pred)
    fn = np.sum(y_true & ~y_pred)

    precision = (
        tp / (tp + fp)
        if (tp + fp) > 0
        else 0.0
    )

    recall = (
        tp / (tp + fn)
        if (tp + fn) > 0
        else 0.0
    )

    f1 = (
        2.0 * precision * recall
        / (precision + recall)
        if (precision + recall) > 0
        else 0.0
    )

    return {
        "precision": float(precision),
        "recall": float(recall),
        "f1": float(f1),
        "tp": int(tp),
        "fp": int(fp),
        "fn": int(fn),
    }


def evaluate_distance_matrix(D, y_true, percentile):
    """
    Convert LPGW distance matrix into loop-closure predictions.

    For every query segment:

        best_distance = minimum distance to any reference

    Threshold:

        percentile of the complete distance matrix

    Prediction:

        best_distance <= threshold
    """

    D = np.asarray(D, dtype=float)
    y_true = np.asarray(y_true, dtype=bool)

    if D.ndim != 2:
        raise ValueError(
            "Distance matrix must be 2-dimensional."
        )

    if D.shape[0] != len(y_true):
        raise ValueError(
            f"Distance matrix has {D.shape[0]} query rows, "
            f"but y_true has length {len(y_true)}."
        )

    if D.size == 0:
        raise ValueError(
            "Distance matrix is empty."
        )

    if not np.all(np.isfinite(D)):
        raise ValueError(
            "Distance matrix contains NaN or infinite values."
        )

    threshold = np.percentile(
        D,
        percentile,
    )

    best_distance_per_query = np.min(
        D,
        axis=1,
    )

    y_pred = (
        best_distance_per_query <= threshold
    )

    metrics = precision_recall_f1(
        y_true,
        y_pred,
    )

    metrics["threshold_tau"] = float(threshold)

    metrics["num_predicted_positive"] = int(
        np.sum(y_pred)
    )

    return y_pred, metrics


