def load_canonical_ground_truth(num_query_segments):
    """
    Load the canonical ground truth generated by:

        ground_truth/generate_ground_truth.py

    Returns:
        Boolean array indexed by canonical query_index.
    """

    gt_path = (
        Path("ground_truth")
        / "files"
        / (
            f"gt_{config.DATASET_SHORT}_"
            f"{config.SPATIAL_TOLERANCE}m.csv"
        )
    )

    print("\nLoading canonical ground truth:")
    print(f"  {gt_path}")

    if not gt_path.exists():
        raise FileNotFoundError(
            "\nCanonical ground truth was not found:\n"
            f"  {gt_path}\n\n"
            "Run this first:\n"
            "  python ground_truth/generate_ground_truth.py"
        )

    gt_df = pd.read_csv(gt_path)

    required_columns = {
        "query_index",
        "nearest_ref_index",
        "nearest_distance_m",
        "label",
    }

    missing = required_columns - set(gt_df.columns)

    if missing:
        raise ValueError(
            f"Canonical GT is missing columns: {sorted(missing)}"
        )

    gt_df = (
        gt_df
        .sort_values("query_index")
        .reset_index(drop=True)
    )

    expected_indices = np.arange(len(gt_df))
    actual_indices = gt_df["query_index"].to_numpy()

    if not np.array_equal(actual_indices, expected_indices):
        raise ValueError(
            "Canonical GT query indices are not consecutive "
            "starting from zero."
        )

    if len(gt_df) != num_query_segments:
        raise ValueError(
            "\nCanonical GT and experiment segmentation do not match.\n"
            f"Canonical GT query segments: {len(gt_df)}\n"
            f"Experiment query segments:   {num_query_segments}\n\n"
            "This usually means trajectory preprocessing or "
            "segmentation differs between the GT generator "
            "and this experiment."
        )

    y_true = gt_df["label"].to_numpy(dtype=bool)

    print(
        f"  Canonical GT query segments: {len(y_true)}"
    )

    print(
        f"  Canonical GT positives: "
        f"{np.sum(y_true)} / {len(y_true)}"
    )

    print(
        f"  Canonical GT tolerance: "
        f"{config.SPATIAL_TOLERANCE} m"
    )

    return y_true


