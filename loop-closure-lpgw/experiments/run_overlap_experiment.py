RANDOM_SEED = getattr(config, "RANDOM_SEED", 42)


# ---------------------------------------------------------------------
# Canonical ground truth
# ---------------------------------------------------------------------

def load_canonical_ground_truth(tolerance_m: float):
    """
    Load the canonical GT generated by ground_truth/generate_ground_truth.py.

    Returns:
        y_true
        ref_centers
        query_centers
    """

    gt_dir = repo_root / "ground_truth" / "files"

    gt_csv = (
        gt_dir
        / f"gt_{config.DATASET_SHORT}_{tolerance_m}m.csv"
    )

    meta_json = (
        gt_dir
        / f"gt_{config.DATASET_SHORT}_{tolerance_m}m_meta.json"
    )

    if not gt_csv.exists() or not meta_json.exists():
        raise FileNotFoundError(
            f"Canonical ground truth for "
            f"{config.DATASET_SHORT} at {tolerance_m} m not found.\n"
            f"Expected:\n"
            f"  {gt_csv}\n"
            f"  {meta_json}\n"
            f"Run ground_truth/generate_ground_truth.py first."
        )

    gt_df = pd.read_csv(gt_csv)

    with open(meta_json, "r") as f:
        meta = json.load(f)

    y_true = gt_df["label"].to_numpy(dtype=int)

    ref_centers = np.asarray(
        meta["ref_centers"],
        dtype=np.float64,
    )

    query_centers = np.asarray(
        meta["query_centers"],
        dtype=np.float64,
    )

    return y_true, ref_centers, query_centers


# ---------------------------------------------------------------------
# Partial observation
# ---------------------------------------------------------------------

def subsample_segment_points(
    seg: np.ndarray,
    ratio: float,
    rng: np.random.Generator,
    min_points: int = 5,
) -> np.ndarray:
    """
    Randomly retain `ratio` fraction of points from a segment.

    The original point ordering is preserved.
    At least min_points are retained.
    """

    seg = np.asarray(seg)

    n = len(seg)

    keep = max(
        min_points,
        int(np.floor(n * ratio)),
    )

    if keep >= n:
        return seg.copy()

    indices = rng.choice(
        n,
        size=keep,
        replace=False,
    )

    indices.sort()

    return seg[indices]


# ---------------------------------------------------------------------
# Main experiment
# ---------------------------------------------------------------------

def run_overlap_experiment():

    print("=" * 70)
    print("LPGW / DTW PARTIAL-OVERLAP ROBUSTNESS EXPERIMENT")
    print("=" * 70)

    print(f"Dataset: {config.DATASET_LABEL_REF} vs "
          f"{config.DATASET_LABEL_QUERY}")

    print(f"Overlap ratios: [1.0, 0.8, 0.6, 0.4]")
    print(f"Canonical tolerance: {config.SPATIAL_TOLERANCE} m")
    print(f"Percentile: {config.PERCENTILE}%")
    print()

    # -------------------------------------------------------------
    # Paths
    # -------------------------------------------------------------

    poses_dir = repo_root / config.POSES_DIR

    ref_csv = poses_dir / config.BAG3_CSV
    query_csv = poses_dir / config.BAG7_CSV

    # -------------------------------------------------------------
    # Load trajectories
    # -------------------------------------------------------------

    print("Loading trajectories...")

    ref_df = load_trajectory(ref_csv)
    query_df = load_trajectory(query_csv)

    ref_xyz = ref_df[
        ["PosX", "PosY", "PosZ"]
    ].to_numpy(dtype=np.float64)

    query_xyz = query_df[
        ["PosX", "PosY", "PosZ"]
    ].to_numpy(dtype=np.float64)

    print(f"Raw reference points: {len(ref_xyz)}")
    print(f"Raw query points:     {len(query_xyz)}")

    # -------------------------------------------------------------
    # Canonical preprocessing
    # -------------------------------------------------------------

    target_points = config.TARGET_POINTS
    segment_length = config.SEGMENT_LENGTH
    fps = config.FPS
    stride = config.STRIDE
    tolerance = config.SPATIAL_TOLERANCE

    ref_xyz_ds = downsample_trajectory(
        ref_xyz,
        target_points,
    )

    query_xyz_ds = downsample_trajectory(
        query_xyz,
        target_points,
    )

    print()
    print("After downsampling:")
    print(f"  Reference: {len(ref_xyz_ds)}")
    print(f"  Query:     {len(query_xyz_ds)}")

    # -------------------------------------------------------------
    # Canonical segmentation
    # -------------------------------------------------------------

    segments_ref = segment_trajectory(
        ref_xyz_ds,
        segment_length=segment_length,
        fps=fps,
        stride=stride,
    )

    segments_query = segment_trajectory(
        query_xyz_ds,
        segment_length=segment_length,
        fps=fps,
        stride=stride,
    )

    min_len = min(
        len(segments_ref),
        len(segments_query),
    )

    segments_ref = segments_ref[:min_len]
    segments_query = segments_query[:min_len]

    print()
    print(f"Reference segments: {len(segments_ref)}")
    print(f"Query segments:     {len(segments_query)}")

    # -------------------------------------------------------------
    # Load canonical GT
    # -------------------------------------------------------------

    y_true, ref_centers_canonical, query_centers_canonical = (
        load_canonical_ground_truth(tolerance)
    )

    # Make sure the GT and current segmentation have identical size.
    if len(y_true) != min_len:
        raise RuntimeError(
            f"Canonical GT contains {len(y_true)} query labels, "
            f"but current segmentation contains {min_len} query segments."
        )

    # -------------------------------------------------------------
    # Verify segmentation against canonical GT
    # -------------------------------------------------------------

    ref_centers_now = np.array([
        seg.mean(axis=0)
        for seg in segments_ref
    ])

    query_centers_now = np.array([
        seg.mean(axis=0)
        for seg in segments_query
    ])

    if not np.allclose(
        ref_centers_now,
        ref_centers_canonical,
        atol=1e-6,
    ):
        raise RuntimeError(
            "Reference centers differ from canonical GT. "
            "Segmentation/downsampling parameters may have changed."
        )

    if not np.allclose(
        query_centers_now,
        query_centers_canonical,
        atol=1e-6,
    ):
        raise RuntimeError(
            "Query centers differ from canonical GT. "
            "Segmentation/downsampling parameters may have changed."
        )

    print()
    print("Canonical segmentation verified.")
    print(
        f"Canonical GT positives: "
        f"{int(y_true.sum())} / {len(y_true)}"
    )

    # -------------------------------------------------------------
    # Overlap experiment
    # -------------------------------------------------------------

    overlap_ratios = [
        1.0,
        0.8,
        0.6,
        0.4,
    ]

    rows = []

    for ratio in overlap_ratios:

        print()
        print("=" * 70)
        print(f"OVERLAP RATIO = {ratio:.2f}")
        print("=" * 70)

        rng = np.random.default_rng(
            RANDOM_SEED + int(ratio * 1000)
        )

        # ---------------------------------------------------------
        # Partially observe QUERY segments only.
        #
        # Reference segments remain unchanged.
        # Ground truth remains unchanged.
        # ---------------------------------------------------------

        segments_query_sub = [
            subsample_segment_points(
                seg,
                ratio,
                rng,
            )
            for seg in segments_query
        ]

        print(
            f"Query points per segment: "
            f"{len(segments_query_sub[0])}"
        )

        # =========================================================
        # LPGW
        # =========================================================

        print()
        print("Running LPGW...")

        detector = LoopClosureDetector(
            segment_length=config.SEGMENT_LENGTH,
            fps=config.FPS,
            stride=config.STRIDE,
            lambdaa=config.LPGW_LAMBDA,
            downsample_points=config.TARGET_POINTS,
            reference_strategy="robust",
        )

        D_lpgw = detector.compute_distance_matrix(
            segments_query_sub,
            segments_ref,
        )

        y_pred_lpgw, tau_lpgw = detect_with_percentile(
            D_lpgw,
            config.PERCENTILE,
        )

        metrics_lpgw = score_predictions(
            y_true,
            y_pred_lpgw,
        )

        rows.append({
            "overlap_ratio": ratio,
            "method": "LPGW",
            "precision": metrics_lpgw["precision"],
            "recall": metrics_lpgw["recall"],
            "f1": metrics_lpgw["f1"],
            "num_segments": min_len,
            "threshold_tau": tau_lpgw,
        })

        print(
            f"LPGW: "
            f"P={metrics_lpgw['precision']:.3f}, "
            f"R={metrics_lpgw['recall']:.3f}, "
            f"F1={metrics_lpgw['f1']:.3f}"
        )

        # =========================================================
        # DTW
        # =========================================================

        print()
        print("Preparing DTW experiment...")

        if config.BASELINE_SEGMENT_POLICY == "subsample_fixed":

            max_baseline_segments = getattr(
                config,
                "MAX_BASELINE_SEGMENTS",
                150,
            )

            if min_len > max_baseline_segments:

                indices = np.linspace(
                    0,
                    min_len - 1,
                    max_baseline_segments,
                    dtype=int,
                )

            else:

                indices = np.arange(
                    min_len,
                    dtype=int,
                )

        else:

            indices = np.arange(
                min_len,
                dtype=int,
            )

        seg7_dtw = [
            segments_query_sub[i]
            for i in indices
        ]

        seg3_dtw = [
            segments_ref[i]
            for i in indices
        ]

        # ---------------------------------------------------------
        # CRITICAL:
        #
        # Do NOT recompute GT using the partially observed points.
        #
        # Use the canonical labels corresponding to the ORIGINAL
        # segment indices.
        # ---------------------------------------------------------

        y_true_dtw = y_true[indices]

        print(
            f"DTW segments: {len(indices)}"
        )

        print(
            f"DTW GT positives: "
            f"{int(y_true_dtw.sum())} / {len(y_true_dtw)}"
        )

        print("Running DTW...")

        D_dtw = compute_dtw_matrix(
            seg7_dtw,
            seg3_dtw,
        )

        y_pred_dtw, tau_dtw = detect_with_percentile(
            D_dtw,
            config.PERCENTILE,
        )

        metrics_dtw = score_predictions(
            y_true_dtw,
            y_pred_dtw,
        )

        rows.append({
            "overlap_ratio": ratio,
            "method": "DTW",
            "precision": metrics_dtw["precision"],
            "recall": metrics_dtw["recall"],
            "f1": metrics_dtw["f1"],
            "num_segments": len(indices),
            "threshold_tau": tau_dtw,
        })

        print(
            f"DTW:  "
            f"P={metrics_dtw['precision']:.3f}, "
            f"R={metrics_dtw['recall']:.3f}, "
            f"F1={metrics_dtw['f1']:.3f}"
        )

    # -------------------------------------------------------------
    # Save results
    # -------------------------------------------------------------

    results_df = pd.DataFrame(rows)

    out_dir = repo_root / "results"
    out_dir.mkdir(exist_ok=True)

    out_path = (
        out_dir
        / f"overlap_experiment_{config.DATASET_SHORT}.csv"
    )

    results_df.to_csv(
        out_path,
        index=False,
    )

    print()
    print("=" * 70)
    print("OVERLAP EXPERIMENT COMPLETE")
    print("=" * 70)

    print(f"Saved to: {out_path}")

    print()
    print("Final table:")
    print(results_df.to_string(index=False))


if __name__ == "__main__":
    run_overlap_experiment()