# experiments/run_overlap_experiment.py

"""
Partial-overlap robustness experiment.

For each overlap_ratio in [1.0, 0.8, 0.6, 0.4]:

- Keep reference and query segmentation identical to the ratio=1.0 case.
- For each query segment, randomly retain only overlap_ratio fraction
  of its points.
- Recompute LPGW/DTW distances using these partially observed segments.
- Use the SAME canonical ground-truth labels for every overlap ratio.

This tests robustness to partial observation, not changes in ground truth.

Saves:
    results/overlap_experiment_{DATASET_SHORT}.csv
"""

